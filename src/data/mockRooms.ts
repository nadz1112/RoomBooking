import { Room, TimeSlot } from '../types/room';

const STANDARD_TIME_SLOTS: string[] = [
  '07:00 - 09:00',
  '09:15 - 11:15',
  '13:00 - 15:00',
  '15:15 - 17:15',
  '17:30 - 19:30',
  '19:30 - 21:30',
];

const createSlots = (bookedIndices: number[]): TimeSlot[] => {
  return STANDARD_TIME_SLOTS.map((slot, index) => ({
    id: `slot-${index + 1}`,
    timeRange: slot,
    isBooked: bookedIndices.includes(index),
    bookedBy: bookedIndices.includes(index)
      ? `Lớp CNPM ${index + 1} / Giảng viên phụ trách`
      : undefined,
  }));
};

